"""Parser: package clause, imports, declarations, generics, build tags and recovery."""

from __future__ import annotations

import unittest

from aindex.goparse import parse_source
from tests.support import API_GO, BROKEN_GO, MODE_LINUX_GO, ORPHAN_GO, STORE_GO, STORE_TEST_GO

GENERATED_GO = """// Code generated by protoc-gen-go. DO NOT EDIT.

package proto

func Generated() {}
"""

TAGGED_GO = """//go:build linux && amd64
// +build linux,amd64

package platform

func Mode() string { return "linux" }
"""


def parse(text: str, rel_path: str = "x.go"):
    return parse_source(text.encode("utf-8"), rel_path)


class PackageClauseTest(unittest.TestCase):
    def test_name_and_doc_are_read(self) -> None:
        parsed = parse(STORE_GO, "internal/store/store.go")
        self.assertEqual(parsed.package_name, "store")
        self.assertEqual(parsed.package_doc, "Package store keeps items in memory.")

    def test_doc_is_empty_without_a_comment(self) -> None:
        self.assertEqual(parse(STORE_TEST_GO).package_doc, "")

    def test_missing_package_clause_leaves_the_name_empty(self) -> None:
        parsed = parse(ORPHAN_GO, "orphan/nopackage.go")
        self.assertEqual(parsed.package_name, "")
        self.assertEqual(parsed.errors, [])
        self.assertEqual([decl.name for decl in parsed.decls], ["Orphan"])

    def test_line_count_and_rel_path_are_recorded(self) -> None:
        parsed = parse(STORE_GO, "internal/store/store.go")
        self.assertEqual(parsed.rel_path, "internal/store/store.go")
        self.assertEqual(parsed.lines, STORE_GO.count("\n") + 1)


class ImportTest(unittest.TestCase):
    def test_imports_are_read_with_their_lines(self) -> None:
        parsed = parse(STORE_GO)
        self.assertEqual([spec.path for spec in parsed.imports], ["context", "fmt", "sync"])
        self.assertEqual([spec.alias for spec in parsed.imports], ["", "", ""])
        self.assertEqual([spec.line for spec in parsed.imports], [5, 6, 7])
        self.assertEqual(parsed.import_paths, ["context", "fmt", "sync"])

    def test_nested_import_paths_use_the_last_segment_as_local_name(self) -> None:
        parsed = parse(API_GO)
        self.assertEqual(
            [spec.path for spec in parsed.imports],
            ["context", "example.com/demo/internal/store"],
        )
        self.assertEqual(parsed.imports[1].local_name, "store")


class DeclarationTest(unittest.TestCase):
    def test_struct_fields(self) -> None:
        parsed = parse(STORE_GO)
        item = next(decl for decl in parsed.decls if decl.name == "Item")
        self.assertEqual(item.type_kind, "struct")
        self.assertEqual(
            [(field.name, field.type) for field in item.fields],
            [("ID", "string"), ("Kind", "Kind")],
        )
        self.assertEqual(item.signature, "type Item struct")

    def test_interface_methods(self) -> None:
        parsed = parse(STORE_GO)
        store = next(decl for decl in parsed.decls if decl.name == "Store")
        self.assertEqual(store.type_kind, "interface")
        self.assertEqual([method.name for method in store.iface_methods], ["Get"])
        self.assertEqual(
            store.iface_methods[0].signature,
            "Get(ctx context.Context, id string) (Item, error)",
        )

    def test_blank_identifier_declares_nothing(self) -> None:
        # ``var _ Store = (*memory)(nil)`` is a compile-time assertion, not a symbol.
        parsed = parse(STORE_GO)
        self.assertNotIn("_", [decl.name for decl in parsed.decls])

    def test_const_and_var_specs(self) -> None:
        parsed = parse(STORE_GO)
        kinds = {
            decl.name: decl.kind for decl in parsed.decls if decl.kind in ("const", "var")
        }
        self.assertEqual(
            kinds,
            {
                "KindAnswer": "const",
                "KindNote": "const",
                "Version": "const",
                "ErrMissing": "var",
            },
        )

    def test_method_receiver_is_recorded(self) -> None:
        parsed = parse(STORE_GO)
        get = next(decl for decl in parsed.decls if decl.name == "Get")
        self.assertEqual(get.kind, "method")
        self.assertEqual(get.receiver, "*memory")
        self.assertEqual(get.receiver_var, "m")
        self.assertEqual(get.receiver_type, "memory")
        self.assertEqual(
            get.signature, "func (m *memory) Get(ctx context.Context, id string) (Item, error)"
        )

    def test_function_signature_excludes_the_body(self) -> None:
        parsed = parse(STORE_GO)
        put = next(decl for decl in parsed.decls if decl.name == "Put")
        self.assertEqual(put.signature, "func (m *memory) Put(item Item)")
        self.assertEqual([param.name for param in put.params], ["item"])

    def test_exported_flag_follows_go_rules(self) -> None:
        parsed = parse(STORE_GO)
        exported = {decl.name: decl.exported for decl in parsed.decls}
        self.assertTrue(exported["Item"])
        self.assertFalse(exported["memory"])
        self.assertFalse(exported["save"])

    def test_test_functions_are_marked(self) -> None:
        parsed = parse(STORE_TEST_GO, "internal/store/store_test.go")
        self.assertEqual([decl.kind for decl in parsed.decls], ["test"])
        self.assertTrue(parsed.decls[0].test_related)
        self.assertTrue(parsed.decls[0].exported)


    def test_docs_are_attached_to_declarations(self) -> None:
        parsed = parse(STORE_GO)
        docs = {decl.name: decl.doc for decl in parsed.decls}
        self.assertEqual(docs["Item"], "Item is one stored value.")
        self.assertEqual(docs["Kind"], "Kind classifies items.")
        self.assertEqual(docs["Store"], "Store is the read side of the store.")
        self.assertEqual(docs["Version"], "Version of the store implementation.")
        self.assertEqual(docs["ErrMissing"], "ErrMissing is returned for unknown ids.")
        self.assertEqual(docs["New"], "New returns an empty in-memory store.")

    def test_group_doc_is_carried_to_every_spec(self) -> None:
        parsed = parse(STORE_GO)
        docs = {decl.name: decl.doc for decl in parsed.decls}
        self.assertEqual(docs["KindAnswer"], "Item kinds.")
        self.assertEqual(docs["KindNote"], "Item kinds.")

    def test_a_spec_doc_wins_over_the_group_doc(self) -> None:
        text = (
            "package p\n"
            "\n"
            "// Group doc.\n"
            "const (\n"
            "\tA = 1\n"
            "\n"
            "\t// B doc.\n"
            "\tB = 2\n"
            ")\n"
        )
        docs = {decl.name: decl.doc for decl in parse(text).decls}
        self.assertEqual(docs["A"], "Group doc.")
        self.assertEqual(docs["B"], "B doc.")

    def test_the_doc_above_the_keyword_reaches_every_spec(self) -> None:
        # In a ``type``/``var``/``const`` block the comment sits above the
        # keyword rather than above the name, so it has to be read from there.
        text = (
            "package p\n"
            "\n"
            "// V doc.\n"
            "var (\n"
            "\tV = 1\n"
            "\tW = 2\n"
            ")\n"
            "\n"
            "// T doc.\n"
            "type (\n"
            "\tT struct{}\n"
            ")\n"
        )
        docs = {decl.name: decl.doc for decl in parse(text).decls}
        self.assertEqual((docs["V"], docs["W"]), ("V doc.", "V doc."))
        self.assertEqual(docs["T"], "T doc.")

    def test_multi_line_doc_is_kept_verbatim(self) -> None:
        text = (
            "package p\n"
            "\n"
            "// Item is one stored value.\n"
            "// It is used by the store.\n"
            "type Item struct{}\n"
        )
        parsed = parse(text)
        self.assertEqual(
            parsed.decls[0].doc, "Item is one stored value.\nIt is used by the store."
        )

    def test_declaration_without_comment_has_no_doc(self) -> None:
        parsed = parse(STORE_GO)
        save = next(decl for decl in parsed.decls if decl.name == "save")
        self.assertEqual(save.doc, "")

    def test_doc_detached_by_a_blank_line_is_not_attached(self) -> None:
        text = "package p\n\n// Orphan comment.\n\nvar V = 1\n"
        self.assertEqual(parse(text).decls[0].doc, "")


class GenericsTest(unittest.TestCase):
    def test_type_parameters_are_collected(self) -> None:
        parsed = parse(API_GO)
        list_type = next(decl for decl in parsed.decls if decl.name == "List")
        self.assertEqual(list_type.type_params, ("T",))

    def test_generic_receiver_base_type_is_the_bare_name(self) -> None:
        parsed = parse(API_GO)
        push = next(decl for decl in parsed.decls if decl.name == "Push")
        self.assertEqual(push.receiver, "*List[T]")
        self.assertEqual(push.receiver_type, "List")


class BuildTagTest(unittest.TestCase):
    def test_go_build_line_is_collected(self) -> None:
        parsed = parse(MODE_LINUX_GO, "platform/mode_linux.go")
        self.assertEqual(parsed.build_tags, ["go:build linux"])
        self.assertEqual(parsed.package_name, "platform")

    def test_both_constraint_forms_are_collected(self) -> None:
        parsed = parse(TAGGED_GO)
        self.assertEqual(parsed.build_tags, ["go:build linux && amd64", "+build linux,amd64"])

    def test_plain_files_have_no_tags(self) -> None:
        self.assertEqual(parse(STORE_GO).build_tags, [])


class RecoveryTest(unittest.TestCase):
    def test_lexer_error_is_reported_but_declarations_survive(self) -> None:
        parsed = parse(BROKEN_GO, "broken/broken.go")
        self.assertEqual(parsed.errors, ["line 4: unterminated string or rune literal"])
        self.assertEqual(parsed.package_name, "broken")
        self.assertEqual([decl.name for decl in parsed.decls], ["BrokenValue", "StillParsed"])

    def test_generated_marker_is_detected(self) -> None:
        self.assertTrue(parse(GENERATED_GO).generated)
        self.assertFalse(parse(STORE_GO).generated)

    def test_empty_input_is_not_an_exception(self) -> None:
        parsed = parse("")
        self.assertEqual(parsed.package_name, "")
        self.assertEqual(parsed.decls, [])

    def test_content_hash_is_stable_and_content_specific(self) -> None:
        first = parse(STORE_GO, "a.go")
        second = parse(STORE_GO, "b.go")
        self.assertEqual(first.content_hash, second.content_hash)
        self.assertNotEqual(first.content_hash, parse("package other\n").content_hash)
        self.assertEqual(len(first.content_hash), 64)


if __name__ == "__main__":
    unittest.main()
